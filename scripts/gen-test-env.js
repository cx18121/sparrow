#!/usr/bin/env node
// Writes .env.test.local from `supabase status` and ensures the e2e test user
// exists before Playwright starts. Run automatically via `npm run test:e2e`.

import { execSync } from 'child_process'
import { writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'
import { createClient } from '@supabase/supabase-js'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

let status
try {
  status = JSON.parse(execSync('supabase status --output json 2>/dev/null', { cwd: ROOT, encoding: 'utf8' }))
} catch {
  console.error('supabase status failed — is Supabase running? Try: supabase start')
  process.exit(1)
}

const supabaseUrl = status.API_URL
// Prefer the new sb_secret_* SECRET_KEY (forward-looking server key).
// Fall back to legacy SERVICE_ROLE_KEY for older local stacks that
// don't emit SECRET_KEY yet.
const serviceKey = status.SECRET_KEY ?? status.SERVICE_ROLE_KEY

const content = `# Auto-generated by scripts/gen-test-env.js — do not commit
E2E_SUPABASE_URL=${supabaseUrl}
E2E_SUPABASE_ANON_KEY=${status.PUBLISHABLE_KEY ?? status.ANON_KEY}
E2E_SUPABASE_SERVICE_KEY=${serviceKey}
E2E_DB_URL=${status.DB_URL}
`

writeFileSync(resolve(ROOT, '.env.test.local'), content)
console.log('[gen-test-env] .env.test.local written from supabase status')

// Ensure the e2e test user exists before Playwright starts. This runs after
// teardown deletes the user, so the next run starts with the user already present.
const admin = createClient(supabaseUrl, serviceKey, {
  auth: { autoRefreshToken: false, persistSession: false },
})

// Retry — auth container can be briefly unavailable right after supabase
// start / db reset.
let existing = null
let lastErr = null
for (let attempt = 0; attempt < 6; attempt++) {
  const res = await admin.auth.admin.listUsers()
  if (!res.error) { existing = res.data; lastErr = null; break }
  lastErr = res.error
  await new Promise(r => setTimeout(r, 500 * (attempt + 1)))
}
if (lastErr) {
  const detail = lastErr.message || JSON.stringify(lastErr, null, 2) || String(lastErr)
  console.error('[gen-test-env] Could not list users after 6 retries:', detail)
  console.error('Have:', { hasSecretKey: !!status.SECRET_KEY, hasServiceRoleKey: !!status.SERVICE_ROLE_KEY })
  process.exit(1)
}

const alreadyExists = existing?.users?.some(u => u.email === 'e2e@sparrow.test')
if (!alreadyExists) {
  console.log('[gen-test-env] Creating e2e test user...')
  const { error } = await admin.auth.admin.createUser({
    email: 'e2e@sparrow.test',
    password: 'SparrowE2E2024!',
    email_confirm: true,
    user_metadata: { full_name: 'E2E Test User' },
  })
  if (error) {
    console.error('[gen-test-env] Failed to create e2e test user:', error.message)
    process.exit(1)
  }
  console.log('[gen-test-env] E2E test user created.')
} else {
  console.log('[gen-test-env] E2E test user already exists.')
}
